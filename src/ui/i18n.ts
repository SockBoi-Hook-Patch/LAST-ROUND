const DICT: Record<Lang, Record<TextKey, string>> = { th: TH, en: EN };

let current: Lang = 'th';

export function setLang(lang: Lang): void {
  current = lang === 'en' ? 'en' : 'th';
  if (typeof document !== 'undefined') {
    document.documentElement.lang = current;
    document.title = DICT[current]['app.title'];
  }
}

export function getLang(): Lang {
  return current;
}

export function detectLang(): Lang {
  // Thai if it appears anywhere in the browser's language list.
  try {
    if (typeof navigator === 'undefined') return 'th';
    const list = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language];
    if (!list.some((l) => typeof l === 'string' && l.length > 0)) return 'th';
    return list.some((l) => String(l).toLowerCase().startsWith('th')) ? 'th' : 'en';
  } catch {
    return 'th';
  }
}

/** Translate `key`, replacing `{name}` placeholders from `vars`. */
export function t(key: TextKey, vars?: Record<string, string | number>): string {
  let s: string = DICT[current][key] ?? DICT.th[key] ?? key;
  if (vars) for (const k of Object.keys(vars)) s = s.replace(`{${k}}`, String(vars[k]));
  return s;
}

/** Escape text for safe insertion into HTML templates. */
export function esc(text: string): string {
  return text.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c] as string);
}
